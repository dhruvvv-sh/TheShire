%% SWRO PLANT PROCESS FLOW DIAGRAM
% Recreates and exports the baseline process-flow diagram.

clear;
clc;
close all;

% Baseline simulation results
Q.raw = 4213.00;
Q.DAF = 4204.57;
Q.DMF = 4196.16;
Q.CF = 4191.97;
Q.UFpermeate = 3982.37;
Q.UFreject = 209.60;
Q.product = 1911.54;
Q.brine = 2070.83;

TDS.product = 148.17;
TDS.brine = 66128.61;

overallRecovery = 45.37;
saltRejection = 99.57;
netSEC = 2.238;

% Figure layout
fig = figure('Color', 'white', ...
    'Name', 'Figure 1: SWRO Plant Flow Diagram', ...
    'Position', [50 50 1800 900]);
axes('Position', [0 0 1 1], 'Visible', 'off');

annotation('textbox', [0.20 0.88 0.60 0.08], ...
    'String', 'SWRO Desalination Plant - Process Flow Diagram', ...
    'HorizontalAlignment', 'center', 'VerticalAlignment', 'middle', ...
    'FontSize', 24, 'FontWeight', 'bold', 'EdgeColor', 'none');

processColor = [0.86 0.93 0.98];
processEdge = [0.12 0.35 0.62];
productColor = [0.84 0.96 0.87];
productEdge = [0.10 0.55 0.24];
brineColor = [1.00 0.89 0.80];
brineEdge = [0.75 0.25 0.04];
rejectColor = [0.98 0.95 0.82];
rejectEdge = [0.65 0.52 0.18];

y = 0.50;
h = 0.16;
w = 0.125;
x = [0.025 0.175 0.325 0.475 0.625 0.775];

addBox(x(1), y, w, h, processColor, processEdge, ...
    {'SEAWATER INTAKE', sprintf('%.2f m^3/h', Q.raw)});
addBox(x(2), y, w, h, processColor, processEdge, ...
    {'DAF', sprintf('%.2f m^3/h', Q.DAF)});
addBox(x(3), y, w, h, processColor, processEdge, ...
    {'DMF', sprintf('%.2f m^3/h', Q.DMF)});
addBox(x(4), y, w, h, processColor, processEdge, ...
    {'CARTRIDGE FILTER', sprintf('%.2f m^3/h', Q.CF)});
addBox(x(5), y, w, h, processColor, processEdge, ...
    {'UF', sprintf('Permeate: %.2f m^3/h', Q.UFpermeate)});
addBox(x(6), y, w, h, processColor, processEdge, ...
    {'REVERSE OSMOSIS', sprintf('Feed: %.2f m^3/h', Q.UFpermeate)});

for idx = 1:5
    annotation('arrow', [x(idx) + w, x(idx + 1)], ...
        [y + h/2, y + h/2], 'Color', processEdge, 'LineWidth', 2);
end

addBox(0.925, 0.60, 0.14, 0.13, productColor, productEdge, ...
    {'FRESHWATER PRODUCT', sprintf('%.2f m^3/h', Q.product), ...
     sprintf('TDS: %.2f mg/L', TDS.product)});
annotation('arrow', [x(6) + w, 0.925], [y + 0.11, 0.665], ...
    'Color', processEdge, 'LineWidth', 2);

addBox(0.925, 0.31, 0.14, 0.13, brineColor, brineEdge, ...
    {'RO BRINE', sprintf('%.2f m^3/h', Q.brine), ...
     sprintf('TDS: %.2f mg/L', TDS.brine)});
annotation('arrow', [x(6) + w, 0.925], [y + 0.04, 0.375], ...
    'Color', processEdge, 'LineWidth', 2);

addBox(0.625, 0.20, w, 0.10, rejectColor, rejectEdge, ...
    {'UF REJECT', sprintf('%.2f m^3/h', Q.UFreject)});
annotation('arrow', [x(5) + w/2, x(5) + w/2], [y, 0.30], ...
    'Color', processEdge, 'LineWidth', 2);

summaryText = { ...
    sprintf('Overall recovery: %.2f%%     RO salt rejection: %.2f%%', ...
        overallRecovery, saltRejection), ...
    sprintf('Estimated net SEC: %.3f kWh/m^3', netSEC), ...
    'Water and salt balance checks are available in the model output.', ...
    'Prototype only: pretreatment and energy parameters include assumptions.'};
annotation('textbox', [0.30 0.015 0.40 0.14], ...
    'String', summaryText, 'HorizontalAlignment', 'center', ...
    'VerticalAlignment', 'middle', 'FontSize', 13, 'EdgeColor', 'none');

scriptDir = fileparts(mfilename('fullpath'));
imageDir = fullfile(scriptDir, '..', 'images');
if ~exist(imageDir, 'dir')
    mkdir(imageDir);
end
outputPath = fullfile(imageDir, 'plant_flow_diagram.png');
exportgraphics(fig, outputPath, 'Resolution', 180);
fprintf('Saved flow diagram to: %s\n', outputPath);

function addBox(x, y, w, h, fillColor, edgeColor, label)
    annotation('textbox', [x y w h], ...
        'String', label, ...
        'HorizontalAlignment', 'center', ...
        'VerticalAlignment', 'middle', ...
        'FontSize', 12, ...
        'FontWeight', 'bold', ...
        'BackgroundColor', fillColor, ...
        'EdgeColor', edgeColor, ...
        'LineWidth', 1.8, ...
        'FitBoxToText', 'off');
end
